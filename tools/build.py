def js_to_json(src):
    """games.js → JSON: убрать комментарии, взять ключи в кавычки, убрать лишние запятые."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c == '"':                                   # строка — копируем как есть
            j = i + 1
            while src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            out.append(src[i:j + 1]); i = j + 1
        elif src.startswith("//", i):                  # комментарий до конца строки
            while i < n and src[i] != "\n": i += 1
        elif c.isalpha() or c == "_":
            m = re.match(r"[A-Za-z_]\w*", src[i:]); w = m.group(0)
            k = i + len(w)
            while k < n and src[k] in " \t": k += 1
            out.append(json.dumps(w) if k < n and src[k] == ":" else w); i += len(w)
        else:
            out.append(c); i += 1
    s = "".join(out)
    return re.sub(r",(\s*[}\]])", r"\1", s)


def load():
    src = open(os.path.join(ROOT, "games.js"), encoding="utf-8").read()
    site = re.search(r"window\.SITE\s*=\s*(\{.*?\});", src, re.S).group(1)
    games = re.search(r"window\.GAMES\s*=\s*(\[.*\]);", src, re.S).group(1)
    return json.loads(js_to_json(site)), json.loads(js_to_json(games))


def slug(t):
    return re.sub(r"^-|-$", "", re.sub(r"[^a-z0-9]+", "-", t.lower().replace("é", "e")))


def gslug(g):
    return slug(g["title"] + " " + g["platform"])


def post_url(site, tg):
    tg = str(tg or "").strip()
    if not tg: return ""
    if tg.startswith("http"): return tg
    ch = site.get("channel", "").lstrip("@")
    return f"https://t.me/{ch}/{tg}" if ch else ""


def norm(site, g):
    """Как на сайте: нет поста в Telegram → «В процессе»."""
    g = dict(g)
    if not post_url(site, g.get("tg")):
        if g.get("status") != "soon" and not g.get("text"): g["text"] = "done"
        g["status"] = "soon"
    return g


def progress(g):
    if g["status"] == "soon":
        return [("ok", "Текст готов"), ("wip", "В процессе")] if g.get("text") == "done" else [("wip", "В процессе")]
    if g["status"] == "beta":
        return [("ok", "Переведено"), ("half", "Бета-версия")]
    return [("ok", "Переведено"), ("ok", "Проверено")]


def fmt_date(d):
    m = re.match(r"(\d{4})-(\d{2})-(\d{2})$", d or "")
    return f"{m[3]}.{m[2]}.{m[1]}" if m else ""


