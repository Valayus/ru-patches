def index_block(site, games):
    rows = []
    for name, full, _ in PLATS:
        gs = [g for g in games if g["platform"] == name]
        if not gs: continue
        links = ", ".join(f'<a href="{gslug(g)}/">{e(g["title"])}</a>' for g in gs)
        rows.append(f'<p><b>{e(full)}:</b> {links}</p>')
    return ('<nav class="seo-index" aria-label="Все русификаторы">\n'
            '<h2>Все русификаторы</h2>\n' + "\n".join(rows) + "\n</nav>")


def main():
    try: sys.stdout.reconfigure(encoding="utf-8")
    except Exception: pass
    site, games = load()
    games = [norm(site, g) for g in games]
    # удалить старые сгенерированные страницы
    for d in os.listdir(ROOT):
        f = os.path.join(ROOT, d, "index.html")
        if os.path.isfile(f) and GEN_MARK in open(f, encoding="utf-8").read(400):
            shutil.rmtree(os.path.join(ROOT, d))
    seen = set()
    for g in games:
        s = gslug(g)
        if s in seen: sys.exit(f"Повтор адреса страницы: {s}")
        seen.add(s)
        os.makedirs(os.path.join(ROOT, s), exist_ok=True)
        open(os.path.join(ROOT, s, "index.html"), "w", encoding="utf-8", newline="\n").write(game_page(site, g))
    # список игр в index.html
    ip = os.path.join(ROOT, "index.html")
    t = open(ip, encoding="utf-8").read()
    t = re.sub(r"<!-- GAMES-INDEX -->.*?<!-- /GAMES-INDEX -->",
               lambda m: "<!-- GAMES-INDEX -->\n" + index_block(site, games) + "\n<!-- /GAMES-INDEX -->", t, flags=re.S)
    open(ip, "w", encoding="utf-8", newline="\n").write(t)
    # sitemap и robots
    today = date.today().isoformat()
    urls = [BASE] + [BASE + gslug(g) + "/" for g in games]
    sm = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for u, g in zip(urls, [None] + games):
        lm = (g and g.get("date")) or today
        sm.append(f"  <url><loc>{u}</loc><lastmod>{lm}</lastmod></url>")
    sm.append("</urlset>")
    open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf-8", newline="\n").write("\n".join(sm) + "\n")
    open(os.path.join(ROOT, "robots.txt"), "w", encoding="utf-8", newline="\n").write(
        f"User-agent: *\nAllow: /\nSitemap: {BASE}sitemap.xml\n")
    print(f"Готово: {len(games)} страниц игр, sitemap.xml, robots.txt")


if __name__ == "__main__":
    main()
